// Folder: DataAccess/GuardianDataAccess.cs
using System;
using System.Collections.Generic;
using Microsoft.Data.SqlClient;
using ImmunoTrack.Models;

namespace ImmunoTrack.DataAccess
{
    /// <summary>
    /// Talks to the Guardians table. This is the ONLY place Guardian SQL lives.
    /// It does no validation and shows no messages: it just reads and writes data.
    /// All queries are PARAMETERIZED (@Name), which blocks SQL injection.
    /// </summary>
    public class GuardianDataAccess
    {
        private const string SelectColumns =
            "GuardianID, FirstName, MiddleName, LastName, ContactNumber, Address, RelationshipToChild";

        // READ: all guardians
        public List<Guardian> GetAll()
        {
            string sql = $"SELECT {SelectColumns} FROM Guardians ORDER BY LastName, FirstName";
            return ReadGuardians(sql, null);
        }

        // READ: one guardian by ID (returns null if not found)
        public Guardian? GetById(int guardianId)
        {
            string sql = $"SELECT {SelectColumns} FROM Guardians WHERE GuardianID = @GuardianID";
            var parameters = new List<SqlParameter> { new SqlParameter("@GuardianID", guardianId) };

            List<Guardian> result = ReadGuardians(sql, parameters);
            return result.Count > 0 ? result[0] : null;
        }

        // SEARCH: by guardian's name (partial match)
        public List<Guardian> Search(string name)
        {
            string sql = $@"SELECT {SelectColumns} FROM Guardians
                            WHERE (FirstName + ' ' + LastName) LIKE @Search
                               OR (FirstName + ' ' + ISNULL(MiddleName + ' ', '') + LastName) LIKE @Search
                            ORDER BY LastName, FirstName";
            var parameters = new List<SqlParameter> { new SqlParameter("@Search", "%" + name + "%") };

            return ReadGuardians(sql, parameters);
        }

        // CREATE: returns the new GuardianID generated by the database
        public int Add(Guardian guardian)
        {
            const string sql = @"INSERT INTO Guardians
                                    (FirstName, MiddleName, LastName, ContactNumber, Address, RelationshipToChild)
                                 VALUES
                                    (@FirstName, @MiddleName, @LastName, @ContactNumber, @Address, @Relationship);
                                 SELECT CAST(SCOPE_IDENTITY() AS INT);";

            using (SqlConnection connection = DatabaseConnection.GetConnection())
            using (SqlCommand command = new SqlCommand(sql, connection))
            {
                AddParameters(command, guardian);
                connection.Open();
                return (int)command.ExecuteScalar();
            }
        }

        // UPDATE
        public void Update(Guardian guardian)
        {
            const string sql = @"UPDATE Guardians
                                 SET FirstName = @FirstName, MiddleName = @MiddleName, LastName = @LastName,
                                     ContactNumber = @ContactNumber, Address = @Address,
                                     RelationshipToChild = @Relationship
                                 WHERE GuardianID = @GuardianID";

            using (SqlConnection connection = DatabaseConnection.GetConnection())
            using (SqlCommand command = new SqlCommand(sql, connection))
            {
                AddParameters(command, guardian);
                command.Parameters.AddWithValue("@GuardianID", guardian.GuardianID);
                connection.Open();
                command.ExecuteNonQuery();
            }
        }

        // DELETE (the database refuses with error 547 if the guardian still has children)
        public void Delete(int guardianId)
        {
            const string sql = "DELETE FROM Guardians WHERE GuardianID = @GuardianID";

            using (SqlConnection connection = DatabaseConnection.GetConnection())
            using (SqlCommand command = new SqlCommand(sql, connection))
            {
                command.Parameters.AddWithValue("@GuardianID", guardianId);
                connection.Open();
                command.ExecuteNonQuery();
            }
        }

        // ---------- private helpers ----------

        // Runs a SELECT and turns every row into a Guardian object.
        private List<Guardian> ReadGuardians(string sql, List<SqlParameter>? parameters)
        {
            var guardians = new List<Guardian>();

            using (SqlConnection connection = DatabaseConnection.GetConnection())
            using (SqlCommand command = new SqlCommand(sql, connection))
            {
                if (parameters != null)
                    command.Parameters.AddRange(parameters.ToArray());

                connection.Open();
                using (SqlDataReader reader = command.ExecuteReader())
                {
                    while (reader.Read())
                        guardians.Add(MapGuardian(reader));
                }
            }

            return guardians;
        }

        // One database row -> one Guardian object
        private static Guardian MapGuardian(SqlDataReader reader)
        {
            return new Guardian(
                (int)reader["GuardianID"],
                (string)reader["FirstName"],
                reader["MiddleName"] as string,          // NULL in the database becomes null
                (string)reader["LastName"],
                (string)reader["ContactNumber"],
                (string)reader["Address"],
                (string)reader["RelationshipToChild"]);
        }

        // Shared by Add and Update. A null middle name must be sent as DBNull.
        private static void AddParameters(SqlCommand command, Guardian guardian)
        {
            command.Parameters.AddWithValue("@FirstName", guardian.FirstName);
            command.Parameters.AddWithValue("@MiddleName", (object?)guardian.MiddleName ?? DBNull.Value);
            command.Parameters.AddWithValue("@LastName", guardian.LastName);
            command.Parameters.AddWithValue("@ContactNumber", guardian.ContactNumber);
            command.Parameters.AddWithValue("@Address", guardian.Address);
            command.Parameters.AddWithValue("@Relationship", guardian.RelationshipToChild);
        }
    }
}
